// 비속어가 들어 있지만 괜찮은 말 (검사 전에 지움)
const ALLOWED = ['시발점', '보지마', '보지않', '보지도', '보지만', '시바견', '수박새끼', '새끼손가락', '새끼발가락', '고양이새끼', '강아지새끼'];

// 기호를 지운 글자 (keepDigits: '18놈' 같은 말을 잡기 위해 숫자를 남길지)
function compact(s, keepDigits) {
  const t = String(s == null ? '' : s).toLowerCase().normalize('NFC')
    .replace(/[\s_.,!?~@#$%^&*()\-+=[\]{}|\\/:;"'<>`]/g, '');
  return keepDigits ? t : t.replace(/\d/g, '');
}

export function hasProfanity(text) {
  for (const keep of [false, true]) {
    let t = compact(text, keep);
    for (const w of ALLOWED) t = t.split(w).join('');
    if (t && BANNED.some((w) => t.includes(w))) return true;
  }
  return false;
}
